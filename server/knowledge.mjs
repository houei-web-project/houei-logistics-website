export function composeAnswer(question, classified) {
  let topics = Array.isArray(classified) ? [...new Set(classified.filter(t=>Object.hasOwn(answers,t)))].slice(0,3) : [];
  // Explicit topics take precedence over a small model's classification.
  const explicit=[];
  if(/未経験|初心者|研修|同乗|指導/.test(question))explicit.push('experience');
  if(/免許|資格|取得支援/.test(question))explicit.push('license');
  if(/給与|給料|月給|年収|手取り|賞与|ボーナス|福利|待遇/.test(question))explicit.push('salary');
  if(/休日|休み|休暇|土曜|日曜|有給/.test(question))explicit.push('holidays');
  if(/勤務時間|残業|帰宅|夜勤|早朝|拘束|シフト/.test(question))explicit.push('hours');
  if(/見学/.test(question))explicit.push('visit');
  if(/勤務地|住所|どこに/.test(question))explicit.push('location');
  if(explicit.length)topics=explicit.slice(0,3);
  else topics=topics.slice(0,1);
  if(!topics.length)topics=['unknown'];
  return topics.map(t=>answers[t]).join('\n\n');
}

export function selectFacts(question, history = []) {
  const related = [...history.filter(m => m.role === 'user').slice(-2).map(m => m.content), question].join('\n');
  const found = facts.filter(f => f.match.test(related));
  return found.length ? found : facts.filter(f => ['experience','license','visit','apply'].includes(f.id));
}

